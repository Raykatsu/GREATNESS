// Texte comparable : minuscules, sans accents, « œ » → « oe », apostrophes droites, tirets → espaces.
export const norm = s => String(s || "").toLowerCase().replace(/œ/g, "oe").normalize("NFD").replace(/[\u0300-\u036f]/g, "")
  .replace(/[\u2018\u2019`]/g, "'").replace(/[-_\u2013\u2014]/g, " ").replace(/\s+/g, " ").trim();

// Chaque aliment : { id, name, per: { k, p, c, f, fi }, unit: { label, g }, keys: [noms normalisés] }
